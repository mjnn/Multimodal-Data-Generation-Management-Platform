test('admin can open edit page for oms_cabin', async ({ page }) => {
  await loginAsAdmin(page)
  await page.getByTestId('dtype-edit-oms_cabin').click()
  await expect(page.getByTestId('data-type-editor')).toBeVisible({ timeout: 15_000 })
  await expect(page.getByTestId('dtype-id')).toBeDisabled()
  await expect(page.getByTestId('dtype-id')).toHaveValue('oms_cabin')
  await expect(page.getByTestId('overview-composer-list')).toBeVisible()
  await expect(page.getByTestId('overview-composer-detail')).toBeVisible()
  await expect(page.getByTestId('overview-card-cabin_multicam')).toBeVisible()
  await expect(page.getByTestId('overview-card-clip_table')).toBeVisible()
  await expect(page.getByTestId('overview-card-nvh_spl_column')).toHaveCount(0)
  await page.getByTestId('dtype-overview-preset').click()
  const presetDrop = page.locator('.ant-select-dropdown').filter({ visible: true })
  await expect(presetDrop.getByText(/audio_nvh_timeline/)).toBeVisible()
  await presetDrop.getByText(/四通道频谱时间轴/).click()
  await expect(page.getByTestId('overview-card-nvh_spl_column')).toBeVisible()
  await expect(page.getByTestId('overview-card-nvh_spectrum')).toBeVisible()
  await expect(page.getByTestId('overview-card-cabin_multicam')).toHaveCount(0)
  await expect(page.getByTestId('pipe-source-card')).toHaveCount(1)
  await expect(page.getByTestId('pipe-source-row')).toHaveCount(4)
  await expect(page.getByTestId('pipe-source-card').locator('input').first()).toHaveValue('rosbag')
  await expect(page.getByTestId('pipe-step-parse_bag')).toBeVisible()
  await expect(page.getByTestId('pipe-parse-modalities')).toBeVisible()
  await expect(
    page.getByTestId('pipe-step-parse_bag').locator('.pipe-chip').filter({ hasText: /^连续帧$/ }),
  ).toBeVisible()
  await expect(page.getByTestId('pipe-step-parse_bag').locator('.pipe-chip').filter({ hasText: /^\.mp4$/ })).toHaveCount(0)
  await expect(page.getByTestId('pipe-step-parse_bag').locator('.pipe-chip').filter({ hasText: '多模数据' })).toHaveCount(0)
  await expect(page.getByTestId('pipe-step-transcribe')).toBeVisible()
  const asrDrop = page.locator('.ant-select-dropdown').filter({ visible: true })
  await page.getByTestId('pipe-bind-transcribe-in').locator('.ant-select').click()
  await expect(asrDrop.getByTitle('ROSBAG 解析器 · .wav')).toBeVisible()
  await expect(asrDrop.getByTitle('ROSBAG 解析器 · .mp4')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('pipe-step-encode_preview')).toBeVisible()
  await expect(
    page.getByTestId('pipe-step-encode_preview').locator('.pipe-chip').filter({ hasText: /^\.mp4$/ }),
  ).toHaveCount(0)
  await page.getByTestId('pipe-bind-encode_preview-in').locator('.ant-select').click()
  const encodeDrop = page.locator('.ant-select-dropdown').filter({ visible: true })
  await expect(encodeDrop.getByTitle('ROSBAG 解析器 · .mp4')).toHaveCount(0)
  await expect(encodeDrop.getByTitle('ROSBAG 解析器 · 连续帧')).toBeVisible()
  await expect(encodeDrop.getByTitle('视频抽帧 · 连续帧')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('pipe-bind-transcribe-in').locator('.ant-select-multiple')).toHaveCount(0)
  const labelBind = page.getByTestId('pipe-bind-label-in')
  await expect(labelBind.locator('.ant-select-multiple')).toBeVisible()
  await expect(labelBind.getByTitle('ROSBAG 解析器 · 连续帧')).toBeVisible()
  await expect(labelBind.getByTitle('ROSBAG 解析器 · .wav')).toBeVisible()
  await expect(labelBind.getByTitle('音频 ASR · ASR 文本')).toBeVisible()
  await expect(page.getByTestId('pipe-step-label')).toBeVisible()
})
